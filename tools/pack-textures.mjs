#!/usr/bin/env node
// Packs assets/textures/*.png (16x16 each, named after the game's textures) and assets/skins/*.png
// (64x64 creature skins) into src/tex/packdata.js, which the game uses in place of drawing those
// from code. Run it after changing the pictures (tools/import-textures.mjs makes them from the
// resource packs; any PNG put there by hand works too). Each picture is stored as its palette and
// one index per pixel.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodePNG } from './png.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// A picture as [colours - 1][colours x RGBA][a 4-bit (up to 16 colours) or 8-bit index per pixel].
function packPicture(file, size) {
  const { width, height, data } = decodePNG(readFileSync(file));
  if (width !== size || height !== size) throw new Error(`${file} is ${width}x${height}, not ${size}x${size}`);
  const n2 = size * size, colours = new Map(), idx = new Uint8Array(n2);
  for (let i = 0; i < n2; i++) {
    // (see-through pixels all count as one colour)
    const key = data[i * 4 + 3] === 0 ? 0 : ((data[i * 4] << 24) | (data[i * 4 + 1] << 16) | (data[i * 4 + 2] << 8) | data[i * 4 + 3]) >>> 0;
    if (!colours.has(key)) colours.set(key, colours.size);
    idx[i] = colours.get(key);
  }
  if (colours.size > 256) throw new Error(`${file} has more than 256 colours`);
  const n = colours.size, small = n <= 16;
  const buf = Buffer.alloc(1 + n * 4 + (small ? n2 / 2 : n2));
  buf[0] = n - 1;
  for (const [key, k] of colours) buf.writeUInt32BE(key, 1 + k * 4);
  const at = 1 + n * 4;
  if (small) for (let i = 0; i < n2; i += 2) buf[at + (i >> 1)] = (idx[i] << 4) | idx[i + 1];
  else buf.set(idx, at);
  return buf;
}
let out = '// Generated by tools/pack-textures.mjs from assets/textures and assets/skins (credits in assets/CREDITS.md).\n';
out += '// Textures from Pixel Perfection and Mineclonia, CC BY-SA 4.0. Do not edit by hand.\n';
out += '// Each: [colours - 1][colours x RGBA][a 4-bit (up to 16 colours) or 8-bit index per pixel], base64.\n';
let bytes = 0, count = 0;
for (const [name, dir, size] of [['PACK', 'textures', 16], ['SKIN_PACK', 'skins', 64]]) {
  const files = readdirSync(join(root, 'assets', dir)).filter((f) => f.endsWith('.png')).sort();
  out += `export const ${name} = {\n`;
  for (const f of files) {
    const buf = packPicture(join(root, 'assets', dir, f), size);
    bytes += buf.length; count++;
    out += `  ${f.slice(0, -4)}: '${buf.toString('base64')}',\n`;
  }
  out += '};\n';
}
writeFileSync(join(root, 'src', 'tex', 'packdata.js'), out);
console.log(`src/tex/packdata.js  ${count} pictures, ${Math.round(bytes / 1024)} KB of pixels, ${Math.round(out.length / 1024)} KB of source`);
